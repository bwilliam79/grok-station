#!/usr/bin/env python3
"""Write admin/web/deploy-pins.js for one release.

The input is the commit that holds scripts/update-manifest.txt (`update_commit`). `commit` is never typed in:
it is read from that manifest's `update` line, because a bot renders its instructions with that commit
(gs-update.sh `upd_commit`) and the station renders with `commit`, so they must be the same id. 0.13.4 to
0.13.6 pinned the manifest commit instead, and every paired bot read "instructions don't match" after Update.

Each hash is sha256 of `git show <sha>:<path>` (the blob at that commit, not the
work tree and not a branch name). The admin page copies these hashes into the
deploy prompt. It does not fetch them.

Usage: tools/gen-deploy-pins.py --update-commit <40-char manifest commit> [--out PATH|-]
"""
import argparse
import hashlib
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_OUT = os.path.join(ROOT, "admin", "web", "deploy-pins.js")
FILES = (
    "tools/grok-station-reply",
    "scripts/gs-seal-setup",
    "scripts/gs-seal-reply",
    "scripts/gs_seal_common.py",
    "scripts/vendor-lock.txt",
    "scripts/install-home.sh",
    "scripts/gs-update.sh",
)
_SHA = re.compile(r"^[0-9a-f]{40}$")


def blob(repo, sha, path):
    """Raw bytes of path at sha. Raises if the object or path is missing."""
    return subprocess.check_output(["git", "-C", repo, "show", "%s:%s" % (sha, path)])


def render(sha, digests, update_commit):
    lines = [
        "// Generated by tools/gen-deploy-pins.py. Do not edit by hand.",
        "// sha256 of each file at this commit (`git show <commit>:<path>`). Embedded in the deploy prompt; not fetched.",
        "var DEPLOY_PINS = {",
        '  commit: "%s",' % sha,
        '  update_commit: "%s",' % update_commit,
        "  files: {",
    ]
    keys = list(digests)
    for i, path in enumerate(keys):
        comma = "," if i < len(keys) - 1 else ""
        lines.append('    "%s": "%s"%s' % (path, digests[path], comma))
    lines.extend(["  }", "};", ""])
    return "\n".join(lines)


_UPDATE = re.compile(rb"^update ([0-9a-f]{40}) ([0-9a-f]{64})$", re.M)


def manifest_update(repo, update_commit):
    """(commit, gs-update.sh sha256) from the update line of the manifest at update_commit. Exits on anything off."""
    if not isinstance(update_commit, str) or not _SHA.fullmatch(update_commit):
        raise SystemExit("gen-deploy-pins: --update-commit must be 40 lowercase hex characters")
    try:
        man = blob(repo, update_commit, "scripts/update-manifest.txt")
    except subprocess.CalledProcessError:
        raise SystemExit("gen-deploy-pins: no update manifest at %s" % update_commit)
    found = _UPDATE.findall(man)
    if len(found) != 1:
        raise SystemExit("gen-deploy-pins: the manifest at %s needs exactly one update line" % update_commit)
    sha, want = found[0][0].decode(), found[0][1].decode()
    try:
        script = blob(repo, sha, "scripts/gs-update.sh")
    except subprocess.CalledProcessError:
        raise SystemExit("gen-deploy-pins: no gs-update.sh at the manifest's update commit %s" % sha)
    if hashlib.sha256(script).hexdigest() != want:
        raise SystemExit("gen-deploy-pins: gs-update.sh at %s does not match the manifest" % sha)
    return sha, want


def pins_for(repo, update_commit):
    """deploy-pins.js text: commit = the manifest's update commit, update_commit = the manifest commit."""
    sha, _ = manifest_update(repo, update_commit)
    digests = {}
    for path in FILES:
        try:
            data = blob(repo, sha, path)
        except subprocess.CalledProcessError:
            raise SystemExit("gen-deploy-pins: no blob %s:%s" % (sha, path))
        digests[path] = hashlib.sha256(data).hexdigest()
    return render(sha, digests, update_commit)


def main(argv):
    p = argparse.ArgumentParser(description="Write deploy-pins.js from git blobs at a commit.")
    p.add_argument("sha", nargs="?", help=argparse.SUPPRESS)
    p.add_argument("--repo", default=ROOT, help="repository root (default: this repo)")
    p.add_argument("--update-commit", required=True, help="commit holding scripts/update-manifest.txt")
    p.add_argument("--out", default=DEFAULT_OUT, help="output path, or - for stdout")
    args = p.parse_args(argv)
    if args.sha is not None:
        raise SystemExit("gen-deploy-pins: no commit argument; the pinned commit is read from the manifest's update "
                         "line. Pass only --update-commit <manifest commit>.")
    text = pins_for(args.repo, args.update_commit.strip())
    if args.out == "-":
        sys.stdout.write(text)
        return 0
    parent = os.path.dirname(os.path.abspath(args.out))
    if parent and not os.path.isdir(parent):
        raise SystemExit("gen-deploy-pins: no directory %s" % parent)
    tmp = args.out + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    os.replace(tmp, args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
