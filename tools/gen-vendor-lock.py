#!/usr/bin/env python3
"""Write scripts/vendor-lock.txt from PyPI's JSON for the pinned versions.

Run this by hand when a pin changes. It fetches https://pypi.org only, with
urllib's default certificate checks, and records the sha256 of every file
PyPI publishes for that version. Tests do not run it, and this file does not
contact the network unless you execute it.

  python3 tools/gen-vendor-lock.py
  python3 tools/gen-vendor-lock.py --out -

The versions below are the ones home mode should install. The lock file in
the tree stays at the last hashes that were actually fetched. Do not invent
a hash.
"""
import argparse
import json
import os
import re
import sys
import urllib.request
from urllib.parse import urlsplit

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_OUT = os.path.join(ROOT, "scripts", "vendor-lock.txt")

# Home mode pins. pynacl stays. cffi and pycparser are the versions to lock
# once their published hashes have been fetched.
PINS = (
    ("pynacl", "1.5.0"),
    ("cffi", "2.0.0"),
    ("pycparser", "2.23"),
)
_NAME = re.compile(r"^[a-z0-9][a-z0-9_.-]{0,63}$")
_VER = re.compile(r"^[A-Za-z0-9_.!+-]{1,64}$")
_SHA = re.compile(r"^[0-9a-f]{64}$")


def release_url(name, version):
    if _NAME.fullmatch(name) is None or _VER.fullmatch(version) is None:
        raise SystemExit("gen-vendor-lock: bad pin %s==%s" % (name, version))
    return "https://pypi.org/pypi/%s/%s/json" % (name, version)


def fetch_json(url, opener=None):
    """GET one https URL. opener is injectable so a caller can avoid the network."""
    parts = urlsplit(url)
    if parts.scheme != "https" or parts.hostname != "pypi.org" or parts.username or parts.password:
        raise SystemExit("gen-vendor-lock: refusing %s" % url)
    if parts.query or parts.fragment:
        raise SystemExit("gen-vendor-lock: refusing %s" % url)
    get = opener.open if opener is not None else urllib.request.urlopen
    with get(url, timeout=60) as resp:
        raw = resp.read(4 * 1024 * 1024 + 1)
    if len(raw) > 4 * 1024 * 1024:
        raise SystemExit("gen-vendor-lock: response too large")
    try:
        doc = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError):
        raise SystemExit("gen-vendor-lock: PyPI did not return JSON")
    if not isinstance(doc, dict):
        raise SystemExit("gen-vendor-lock: PyPI did not return an object")
    return doc


def hashes_from_doc(doc):
    """sha256 of every published file, sorted, duplicates dropped."""
    urls = doc.get("urls") if isinstance(doc, dict) else None
    if not isinstance(urls, list) or not urls:
        raise SystemExit("gen-vendor-lock: release has no files")
    found = []
    for item in urls:
        if not isinstance(item, dict):
            continue
        digests = item.get("digests")
        digest = digests.get("sha256") if isinstance(digests, dict) else None
        if not isinstance(digest, str) or _SHA.fullmatch(digest) is None:
            continue
        found.append(digest)
    unique = sorted(set(found))
    if not unique:
        raise SystemExit("gen-vendor-lock: release has no sha256 digests")
    return unique


def render(rows):
    """rows is (name, version, [sha256, ...]). The lock parser accepts this shape."""
    if not rows:
        raise SystemExit("gen-vendor-lock: no packages")
    lines = [
        "# gs-seal-reply vendor lock (PyNaCl + deps), all published files for these versions.",
        "# Generated by tools/gen-vendor-lock.py from PyPI JSON. Do not edit by hand.",
        "# gs-seal-setup vendor-install reads this file. It does not use pip.",
    ]
    for name, version, hashes in rows:
        if _NAME.fullmatch(name) is None or _VER.fullmatch(version) is None or not hashes:
            raise SystemExit("gen-vendor-lock: bad row %s==%s" % (name, version))
        lines.append("%s==%s \\" % (name, version))
        ordered = list(hashes)
        for i, digest in enumerate(ordered):
            if _SHA.fullmatch(digest) is None:
                raise SystemExit("gen-vendor-lock: bad hash for %s" % name)
            slash = " \\" if i < len(ordered) - 1 else ""
            lines.append("    --hash=sha256:%s%s" % (digest, slash))
    lines.append("")
    return "\n".join(lines)


def build(pins=PINS, fetch=None):
    rows = []
    for name, version in pins:
        url = release_url(name, version)
        doc = fetch(url) if fetch is not None else fetch_json(url)
        rows.append((name, version, hashes_from_doc(doc)))
    return render(rows)


def main(argv):
    p = argparse.ArgumentParser(description="Write vendor-lock.txt from PyPI JSON.")
    p.add_argument("--out", default=DEFAULT_OUT, help="output path, or - for stdout")
    args = p.parse_args(argv)
    text = build()
    if args.out == "-":
        sys.stdout.write(text)
        return 0
    parent = os.path.dirname(os.path.abspath(args.out))
    if parent and not os.path.isdir(parent):
        raise SystemExit("gen-vendor-lock: no directory %s" % parent)
    tmp = args.out + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    os.replace(tmp, args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
